void main() {
    init_lynx();
    graphics_init(1);
    graphics_set_palette(palette);

    spr_ctrl[5] = lynx;
    spr_ctrl[6] = lynx >> 8;
    
    cls_ctrl[5] = pixel;
    cls_ctrl[6] = pixel >> 8;

    unsigned char x_pos = 1;
    unsigned char y_pos = 1;
    char sign_x = 1;
    char sign_y = 1;

    while(1) {
        if (!graphics_swap_requested()) {
            if (x_pos < 1) { sign_x = 1; }
            else if (x_pos > 80) { sign_x = -1; }
            if (y_pos < 1) { sign_y = 1; }
            else if (y_pos > 90) { sign_y = -1; }

            x_pos += sign_x;
            y_pos += sign_y;

            spr_ctrl[7] = x_pos;
            spr_ctrl[9] = y_pos;

            graphics_draw_sprite_wait(cls_ctrl);
            graphics_draw_sprite_wait(spr_ctrl);
            graphics_request_swap();
        }
    }
}
